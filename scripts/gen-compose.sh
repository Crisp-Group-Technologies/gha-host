#!/usr/bin/env bash
# gen-compose.sh - render docker-compose.yml for RUNNER_COUNT runners.
# Usage: gen-compose.sh [OUTPUT_FILE]   (default: $GHA_HOME/compose/docker-compose.yml, "-" for stdout)
set -euo pipefail
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SELF_DIR/lib/common.sh"
load_config

[[ -n ${GH_ORG:-} ]] || die "GH_ORG is not set"
[[ -n ${RUNNER_IMAGE:-} ]] || die "RUNNER_IMAGE is not set"
DGID="$(docker_gid)"
[[ -n $DGID ]] || die "no 'docker' group on this host; is Docker installed?"
WORK_ROOT="$DATA_DIR/work"

q() { # YAML double-quoted scalar
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '"%s"' "$s"
}

render() {
  echo "# Generated by gen-compose.sh. Do not edit; change /etc/gha-host/gha-host.env and re-run install.sh."
  echo "name: gha-host"
  echo "services:"
  local i labels
  for ((i = 1; i <= RUNNER_COUNT; i++)); do
    labels="$RUNNER_LABELS"
    [[ $RUNNER_PER_INDEX_LABEL == true ]] && labels="$labels,runner-$i"
    # The workspace is mounted at the SAME path inside and outside the container, so
    # `docker run -v $GITHUB_WORKSPACE:...` and container jobs resolve on the host daemon.
    cat <<EOF
  runner-$i:
    image: $(q "$RUNNER_IMAGE")
    pull_policy: missing
    container_name: gha-runner-$i
    hostname: $(q "$HOST_NAME-$i")
    init: true
    restart: unless-stopped
    stop_grace_period: 2m
    group_add:
      - $(q "$DGID")
    labels:
      gha-host.runner: "true"
    logging:
      driver: json-file
      options:
        max-size: "50m"
        max-file: "3"
    environment:
      GH_ORG: $(q "$GH_ORG")
      GH_API_URL: $(q "$GH_API_URL")
      GH_SERVER_URL: $(q "$GH_SERVER_URL")
      GH_AUTH: $(q "$GH_AUTH")
      GH_APP_ID: $(q "${GH_APP_ID:-}")
      GH_APP_INSTALLATION_ID: $(q "${GH_APP_INSTALLATION_ID:-}")
      GH_APP_KEY_FILE: "/run/gha-secrets/app-key"
      GH_PAT_FILE: "/run/gha-secrets/pat"
      RUNNER_NAME: $(q "$HOST_NAME-$i")
      RUNNER_LABELS: $(q "$labels")
      RUNNER_GROUP: $(q "$RUNNER_GROUP")
      RUNNER_MODE: $(q "$RUNNER_MODE")
      RUNNER_WORKDIR: $(q "$WORK_ROOT/$i")
      RUNNER_DISABLE_UPDATE: $(q "$RUNNER_DISABLE_UPDATE")
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - $(q "$GHA_RUN_SECRETS:/run/gha-secrets:ro")
      - $(q "$WORK_ROOT/$i:$WORK_ROOT/$i")
EOF
    if [[ -n ${RUNNER_EXTRA_VOLUMES:-} ]]; then
      local v
      IFS=',' read -r -a _vols <<<"$RUNNER_EXTRA_VOLUMES"
      for v in "${_vols[@]}"; do [[ -n $v ]] && echo "      - $(q "$v")"; done
    fi
    [[ -n ${RUNNER_CPUS:-} ]] && echo "    cpus: $(q "$RUNNER_CPUS")"
    [[ -n ${RUNNER_MEMORY:-} ]] && echo "    mem_limit: $(q "$RUNNER_MEMORY")"
  done
}

out="${1:-$GHA_HOME/compose/docker-compose.yml}"
if [[ $out == - ]]; then
  render
else
  mkdir -p "$(dirname "$out")"
  render >"$out.tmp"
  mv "$out.tmp" "$out"
  # per-runner workspaces, owned by the runner user
  for ((i = 1; i <= RUNNER_COUNT; i++)); do
    mkdir -p "$WORK_ROOT/$i"
    chown "$RUNNER_UID:$RUNNER_UID" "$WORK_ROOT/$i" 2>/dev/null || true
  done
  log "wrote $out ($RUNNER_COUNT runners)"
fi
